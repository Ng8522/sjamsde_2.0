const fallbackGlob = import.meta.glob<string>("../assets/event/**/*.{jpeg,jpg,JPG}", {
  eager: true,
  query: "?url",
  import: "default",
});

function imagesFromGlob(folder: string): string[] {
  return Object.entries(fallbackGlob)
    .filter(([path]) => path.replace(/\\/g, "/").includes(folder))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([, url]) => url);
}

export function getGalleryAlbumImages(albumId: string): string[] {
  const explicit = albumImages[albumId];
  if (explicit?.length) return explicit;

  const folder = albumId === "bls-mppwp-2025" ? BLS_MPPWP_FOLDER : undefined;
  if (!folder) return [];

  return imagesFromGlob(folder);
}

export function getGalleryAlbumCover(albumId: string): string | undefined {
  return getGalleryAlbumImages(albumId)[0];
}
